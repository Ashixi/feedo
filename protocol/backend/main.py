@app.post("/internal/vector/query")
async def vector_query(req: VectorQueryRequest, request: Request, api_key = Depends(get_api_key)):
    if not EXPOSE_VECTOR_API:
        raise HTTPException(status_code=403, detail="Vector API not exposed")
        
    pubkey = request.headers.get("X-P2P-Pubkey")
    if pubkey and p2p and hasattr(p2p, "reputation"):
        p2p.reputation.charge_peer(pubkey, req.k)
        p2p.reputation.can_afford(pubkey, req.k)

        
    k_limit = getattr(request.state, "k_limit", 20)
    actual_k = min(req.k, k_limit)
    VECTOR_QUERIES.labels(role=request.state.role.value, status="success").inc()
    
    results = []
    if brain:
        try:
            res = brain.table.search(req.vector).limit(actual_k).to_list()
            post_ids = [r["post_id"] for r in res if "hash_id" not in r]
            id_to_hash = {}
            if post_ids:
                async with AsyncSessionLocal() as db:
                    stmt = select(Post.id, Post.hash_id).where(Post.id.in_(post_ids))
                    post_rows = (await db.execute(stmt)).all()
                    id_to_hash = {row.id: row.hash_id for row in post_rows}
            
            seen_hashes = set()
            for r in res:
                similarity = 1.0 - (r["_distance"] / 2.0)
                if similarity >= req.threshold:
                    h_id = r.get("hash_id") or id_to_hash.get(r["post_id"])
                    if h_id and h_id not in seen_hashes:
                        seen_hashes.add(h_id)
                        results.append({"hash_id": h_id, "score": similarity})
        except Exception as e:
            logger.error(f"Vector query error: {e}")
            VECTOR_QUERIES.labels(role=request.state.role.value, status="error").inc()
            raise HTTPException(status_code=500, detail=str(e))
    return results


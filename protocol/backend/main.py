    # Cryptographic Handshake (Client-to-Node)
    author = payload.get("author") or payload.get("author_address")
    hash_id = payload.get("hash_id")
    signature = payload.get("signature")
    if not author or not hash_id or not signature:
        raise HTTPException(status_code=400, detail="Missing author, hash_id, or signature")
    
    if not verify_signature(hash_id, signature, author):
        raise HTTPException(status_code=401, detail="Invalid cryptographic signature")

    # PoW Protection for new users
    author_clean = _normalize_wallet_address(author)
    stmt = select(User).where(User.wallet_address == author_clean)
    user = (await db.execute(stmt)).scalar_one_or_none()
    

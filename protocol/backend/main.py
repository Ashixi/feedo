def _ensure_users_schema_columns(sync_conn) -> None:
    inspector = inspect(sync_conn)
    if not inspector.has_table("users"):
        Base.metadata.create_all(bind=sync_conn)
        inspector = inspect(sync_conn)

    columns = {column["name"] for column in inspector.get_columns("users")}
    if "public_id" not in columns:
        sync_conn.execute(text("ALTER TABLE users ADD COLUMN public_id VARCHAR"))

        user_rows = sync_conn.execute(text("SELECT id FROM users")).fetchall()
        for row in user_rows:
            sync_conn.execute(
                text("UPDATE users SET public_id = :public_id WHERE id = :id"),
                {"id": row.id, "public_id": f"user_{uuid.uuid4().hex[:8]}"},
            )

        sync_conn.execute(
            text("CREATE UNIQUE INDEX IF NOT EXISTS ix_users_public_id ON users (public_id)")
        )

        if sync_conn.dialect.name != "sqlite":
            sync_conn.execute(text("ALTER TABLE users ALTER COLUMN public_id SET NOT NULL"))

    if "privacy" not in columns:
        sync_conn.execute(text("ALTER TABLE users ADD COLUMN privacy VARCHAR(20) DEFAULT 'everyone'"))
        columns.add("privacy")

        if sync_conn.dialect.name != "sqlite":
            sync_conn.execute(text("ALTER TABLE users ALTER COLUMN privacy SET NOT NULL"))

    if "api_url" not in columns:
        sync_conn.execute(text("ALTER TABLE users ADD COLUMN api_url VARCHAR"))
        
    if "indexed_posts_count" not in columns:
        sync_conn.execute(text("ALTER TABLE users ADD COLUMN indexed_posts_count INTEGER DEFAULT 0"))
        
    if "user_vector" not in columns:
        sync_conn.execute(text("ALTER TABLE users ADD COLUMN user_vector JSON"))
        
    if "last_vector_updated_at" not in columns:
        sync_conn.execute(text("ALTER TABLE users ADD COLUMN last_vector_updated_at TIMESTAMP WITH TIME ZONE"))
        
    if "is_admin" not in columns:
        sync_conn.execute(text("ALTER TABLE users ADD COLUMN is_admin BOOLEAN DEFAULT FALSE"))
        
    if "preferred_tags" not in columns:
        sync_conn.execute(text("ALTER TABLE users ADD COLUMN preferred_tags JSON DEFAULT '[]'::json"))
    else:
        # Check type and fix if it's an array from previous buggy migration
        try:
            with sync_conn.begin_nested():
                sync_conn.execute(text("ALTER TABLE users ALTER COLUMN preferred_tags TYPE JSON USING array_to_json(preferred_tags)"))
        except Exception:
            pass # Already JSON or cast failed
            
    if "preferred_languages" not in columns:
        sync_conn.execute(text("ALTER TABLE users ADD COLUMN preferred_languages JSON DEFAULT '[]'::json"))
    else:
        try:
            with sync_conn.begin_nested():
                sync_conn.execute(text("ALTER TABLE users ALTER COLUMN preferred_languages TYPE JSON USING array_to_json(preferred_languages)"))
        except Exception:
            pass
        
    if "saved_chats" not in columns:
        sync_conn.execute(text("ALTER TABLE users ADD COLUMN saved_chats JSON DEFAULT '[]'::json"))

    if "privacy" in columns:
        sync_conn.execute(
            text("UPDATE users SET privacy = LOWER(privacy) WHERE privacy IS NOT NULL AND privacy != LOWER(privacy)")
        )
        sync_conn.execute(
            text("UPDATE users SET privacy = 'everyone' WHERE privacy IS NULL")
        )


def _to_naive_utc(value: datetime) -> datetime:
    if value.tzinfo is None:
        return value
    return value.astimezone(timezone.utc).replace(tzinfo=None) 


async def _make_unique_username(db: AsyncSession, base_username: str) -> str:
    normalized = re.sub(r"[^a-zA-Z0-9_]+", "_", base_username).strip("_") or "user"
    candidate = normalized
    suffix = 1

    while True:
        stmt = select(User).where(User.username == candidate)
        existing = (await db.execute(stmt)).scalar_one_or_none()
        if not existing:
            return candidate
        candidate = f"{normalized}_{suffix}"
        suffix += 1



class PbftCommitRequest(BaseModel):
    tx_hash: str
    status: str

@app.post("/internal/pbft_commit")
async def pbft_commit(req: PbftCommitRequest, db: AsyncSession = Depends(get_db)):
    _require_server_variant()
    if req.status != "finalized":
        return {"status": "ignored"}
    
    from models import CreditTransaction, CreditBalance
    
    stmt = select(CreditTransaction).where(CreditTransaction.tx_hash == req.tx_hash)
    existing = (await db.execute(stmt)).scalar_one_or_none()
    if existing:
        return {"status": "already_committed"}
        
    try:
        wallet = "unknown"
        tx_hash_str = req.tx_hash
        
        ctx = CreditTransaction(
            tx_hash=req.tx_hash,
            wallet_address=wallet,
            amount=1,
            reason="PBFT Finalized POUW",
            signature="pbft_consensus"
        )
        db.add(ctx)
        
        balance_stmt = select(CreditBalance).where(CreditBalance.wallet_address == wallet)
        balance = (await db.execute(balance_stmt)).scalar_one_or_none()
        if not balance:
            balance = CreditBalance(wallet_address=wallet, balance=1)
            db.add(balance)
        else:
            balance.balance += 1
            
        await db.commit()
    except Exception as e:
        await db.rollback()
        logger.error(f"PBFT commit failed: {e}")
        
    return {"status": "committed"}



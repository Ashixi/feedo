def _normalize_wallet_address(wallet_address: str) -> str:
    cleaned = wallet_address.strip().lower()
    if cleaned.startswith('0x'):
        cleaned = cleaned[2:]
    if len(cleaned) == 130 and cleaned.startswith('04'):
        cleaned = cleaned[2:]
    return cleaned


async def _load_user_by_wallet(db: AsyncSession, wallet_address: str | None) -> User | None:
    if not wallet_address:
        return None

    normalized = _normalize_wallet_address(wallet_address)
    wallet_variants = (normalized, f"0x{normalized}")
    stmt = select(User).where(func.lower(User.wallet_address).in_(wallet_variants))
    return (await db.execute(stmt)).scalar_one_or_none()


def _display_author_name(author: User | None, original_name: str | None = None, fallback_wallet: str | None = None) -> str:
    if author is not None:
        for value in (author.display_name, author.username):
            if isinstance(value, str) and value.strip():
                return value.strip()
                
    if original_name and isinstance(original_name, str) and original_name.strip():
        return original_name.strip()
        
    if author is not None and author.public_id:
        return author.public_id
        
    if fallback_wallet:
        return fallback_wallet
    return "Unknown Node"


def _author_avatar_url(author: User | None) -> str | None:
    if author is None or not getattr(author, "avatar_media_hash", None):
        return None
    amh = author.avatar_media_hash
    if amh.startswith("http://") or amh.startswith("https://"):
        return amh
    return f"/p2p-media/{amh}"



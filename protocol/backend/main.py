def _media_cache_file_path(media_hash: str) -> str:
    return os.path.join(MEDIA_DISK_CACHE_DIR, media_hash)


def _load_media_from_disk_cache(media_hash: str) -> bytes | None:
    cache_path = _media_cache_file_path(media_hash)
    if not os.path.exists(cache_path):
        return None
    try:
        with open(cache_path, "rb") as media_file:
            return media_file.read()
    except Exception:
        logger.warning("Failed to read cached media from %s", cache_path, exc_info=True)
        return None


def _store_media_to_disk_cache(media_hash: str, media_bytes: bytes) -> None:
    cache_path = _media_cache_file_path(media_hash)
    try:
        with open(cache_path, "wb") as media_file:
            media_file.write(media_bytes)
    except Exception:
        logger.warning("Failed to persist media cache for %s", media_hash, exc_info=True)


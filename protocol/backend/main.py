@app.get("/p2p-media/{media_hash}")
async def get_p2p_media(media_hash: str, size: int | None = None, db: AsyncSession = Depends(get_db)):
    try:
        cached = MEDIA_CACHE.get(media_hash)
        if cached is not None:
            try:
                return Response(content=cached["bytes"], media_type=cached.get("mime", "application/octet-stream"), status_code=200)
            except Exception:
                pass

        disk_cached = _load_media_from_disk_cache(media_hash)
        if disk_cached is not None:
            try:
                media_type = "application/octet-stream"
                stmt = select(Post).where(Post.content_blob_hash == media_hash).limit(1)
                media_post = (await db.execute(stmt)).scalars().first()
                if media_post and media_post.metadata_:
                    media_type = media_post.metadata_.get("media_mime_type", media_type)
                MEDIA_CACHE[media_hash] = {
                    "bytes": disk_cached,
                    "mime": media_type,
                    "size": len(disk_cached),
                }
                return Response(content=disk_cached, media_type=media_type, status_code=200)
            except Exception:
                pass

        stmt = select(Post).where(Post.content_blob_hash == media_hash).limit(1)
        media_post = (await db.execute(stmt)).scalars().first()

        b64_content = None

        if media_post and media_post.is_full_content_loaded:
            b64_content = media_post.text_content
        else:
            media_meta = media_post.metadata_ if (media_post and isinstance(media_post.metadata_, dict)) else {}
            size_candidates: list[int] = []

        def _append_candidate(candidate: Any) -> None:
            if candidate is None:
                return
            try:
                parsed = int(candidate)
            except Exception:
                return
            if parsed <= 0:
                return
            if parsed not in size_candidates:
                size_candidates.append(parsed)

        _append_candidate(size)
        _append_candidate(media_meta.get("media_size") if isinstance(media_meta, dict) else None)
        _append_candidate(media_meta.get("media_b64_size") if isinstance(media_meta, dict) else None)
        if media_post is not None:
            _append_candidate(media_post.content_size)

        for candidate in list(size_candidates):
            inferred_raw = (candidate // 4) * 3
            inferred_b64 = ((candidate + 2) // 3) * 4
            _append_candidate(inferred_raw)
            _append_candidate(inferred_b64)

            if not size_candidates:
                raise HTTPException(status_code=404, detail="media unavailable")

        last_exc = None
        used_size: int | None = None
        for resolved_size in size_candidates:
            for fetch_base in RUST_FETCH_CONTENT_URLS:
                try:
                    async with httpx.AsyncClient() as client:
                        res = await client.get(f"{fetch_base.rstrip('/')}/{media_hash}/{resolved_size}", timeout=12.0)
                    if res.status_code == 200:
                        try:
                            b64_candidate = res.json()
                        except Exception:
                            b64_candidate = None
                        if b64_candidate:
                            b64_content = b64_candidate
                            used_size = resolved_size
                            break
                    elif res.status_code == 404:
                        last_exc = Exception(
                            f"Rust fetch returned 404 Not Found from {fetch_base} (size={resolved_size})"
                        )
                    else:
                        last_exc = Exception(
                            f"Rust fetch returned status {res.status_code} from {fetch_base} (size={resolved_size})"
                        )
                except Exception as e:
                    last_exc = Exception(f"{e} (fetch_base={fetch_base}, size={resolved_size})")
            if b64_content:
                break

            if last_exc is not None and b64_content is None and "404" not in str(last_exc):
                logger.warning(
                    "P2P media reconstruction failed for %s: %s (tried_sizes=%s)",
                    media_hash,
                    last_exc,
                    size_candidates,
                )
                raise HTTPException(status_code=404, detail="media unavailable")

            if not b64_content:
                raise HTTPException(status_code=404, detail="media unavailable")

            if not media_post:
                resolved_size = used_size or size_candidates[0]
                new_media = Post(
                    source_type="media_blob",
                    text_content="",
                    content_size=resolved_size,
                    is_full_content_loaded=False,
                    author_address="network_sync",
                    content_blob_hash=media_hash,
                    hash_id=f"sync_{media_hash}"
                )
                db.add(new_media)
                await db.commit()

        image_data = base64.b64decode(b64_content)
        mime_type = "application/octet-stream"
        if media_post and media_post.metadata_:
            mime_type = media_post.metadata_.get("media_mime_type", mime_type)
        else:
            stmt_parents = select(Post).where(Post.metadata_.isnot(None))
            res = (await db.execute(stmt_parents)).scalars().all()
            for p in res:
                md = p.metadata_ or {}
                if md.get("media_hash") == media_hash and md.get("media_mime_type"):
                    mime_type = md.get("media_mime_type")
                    break

        MEDIA_CACHE[media_hash] = {
            "bytes": image_data,
            "mime": mime_type,
            "size": len(image_data),
        }
        _store_media_to_disk_cache(media_hash, image_data)

        return Response(content=image_data, media_type=mime_type)
    except HTTPException:
        raise
    except Exception as exc:
        logger.exception("Unexpected /p2p-media failure for %s: %s", media_hash, exc)
        raise HTTPException(status_code=404, detail="media unavailable")



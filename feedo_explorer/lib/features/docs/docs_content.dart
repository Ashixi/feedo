## 1. Core Architecture

The Feedo ecosystem now operates on a true Web3 foundation, eliminating centralized social network constraints:

*   **Decentralized Identifiers (DID) & Cryptography:** Every participant (peer) is identified by an ECDSA-based DID. All network interactions are cryptographically signed.
*   **Kademlia DHT & Gossipsub:** The core P2P layer leverages libp2p. Content is routed via Kademlia DHT, while rapid message dissemination relies on Gossipsub.
*   **CRDT Data Structures:** Conflict-free Replicated Data Types ensure that distributed graphs (posts, identities) eventually converge across all nodes without a central database.
*   **PBFT Consensus:** For critical state changes (like reputation updates or epoch transitions), the network employs Practical Byzantine Fault Tolerance (PBFT) among validator nodes.
*   **Data Availability (DA) via Supernodes:** High-capacity nodes (Supernodes) form a hierarchical layer responsible for ensuring large binary vectors and media remain available across the network.

---

## 2. Explorer Components

The newly redesigned Explorer provides critical insights into these layers:

### Network Topology
Monitors the live P2P network. It displays the total active peers and the subset of Supernodes that form the Data Availability Layer.

### Identities (DID)
Lists known network participants. Instead of traditional "User Profiles", you see cryptographic DIDs and their computed **Reputation Scores**. High reputation ensures prioritization during P2P syncing.

### Consensus Logs
A transparent ledger of network agreements. Here you can inspect the history of PBFT rounds, checking the hashes of confirmed blocks and distributed CRDT operations.

### Vector Space & Content Data
Allows developers to query raw content hashes and inspect the semantic embeddings (AI vectors) generated by the LanceDB integration. This is crucial for verifying that semantic search indexing is functioning properly across the swarm.


## 3. Developer Integration

If you are building dApps or integrating AI models using Feedo Data:

### Running an Independent Explorer
The Explorer Backend is completely decoupled from the Feedo Node API.
1. It runs a background `indexer.py` task.
2. It fetches network stats, DIDs, and consensus logs from the Node via HTTP/gRPC.
3. It serves cached, paginated data to this Flutter interface via `localhost:8001/api/v1`.

### Fetching Data for AI
To extract deduplicated, vectorized datasets:
1. Connect to a local Feedo Node using the `feedo_py` SDK.
2. Query the semantic space: `POST /internal/vector/batch_query`.
3. Resolve hashes into raw text via the DHT.

> **Note:** Heavy data consumption requires maintaining a positive DID Reputation. You must contribute bandwidth or unique data to the network to offset your consumption.


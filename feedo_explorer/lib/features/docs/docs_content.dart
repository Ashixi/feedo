# Feedo Protocol & Explorer Documentation

Welcome to the Feedo Explorer! Feedo has evolved into a robust decentralized protocol, functioning as a peer-to-peer (P2P) network for content aggregation, AI-driven vectorization, and data synchronization.

This Explorer is a dedicated, read-only interface connected to an isolated **Explorer Backend (Indexer)**. It is designed to visualize the real-time state of the network without overwhelming the core P2P nodes.

